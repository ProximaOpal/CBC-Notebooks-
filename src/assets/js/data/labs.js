export function labSlugs(lab) {
  return [lab.slug, ...(lab.aliases || [])];
}

export function findLab(slug) {
  const key = String(slug || "").toLowerCase();
  return LABS.find((lab) => labSlugs(lab).includes(key)) || null;
}
